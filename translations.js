const supportedLanguages = Object.keys(translations);
const select = document.getElementById('language-select');

function matchLanguage(language) {
  if (!language) return 'en';
  const normalized = language.toLowerCase();
  if (normalized.startsWith('zh')) return 'zh-Hant';
  return supportedLanguages.find(code => normalized.startsWith(code.toLowerCase())) || 'en';
}

function setLanguage(language, remember = false) {
  const code = supportedLanguages.includes(language) ? language : matchLanguage(language);
  const text = translations[code];
  document.documentElement.lang = code;
  document.querySelectorAll('[data-i18n]').forEach(element => {
    element.textContent = text[element.dataset.i18n];
  });
  document.querySelectorAll('[data-i18n-html]').forEach(element => {
    element.innerHTML = text[element.dataset.i18nHtml];
  });
  document.title = text.title;
  document.querySelector('meta[name="description"]').content = text.description;
  document.querySelector('meta[property="og:description"]').content = text.description;
  select.value = code;
  select.setAttribute('aria-label', text.languageLabel);
  if (remember) localStorage.setItem('preferred-language', code);
}

const initialLanguage = localStorage.getItem('preferred-language') ||
  navigator.languages?.map(matchLanguage).find(code => supportedLanguages.includes(code)) ||
  matchLanguage(navigator.language);

select.addEventListener('change', event => setLanguage(event.target.value, true));
document.getElementById('year').textContent = new Date().getFullYear();
setLanguage(initialLanguage);
